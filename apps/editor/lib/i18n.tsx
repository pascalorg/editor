export function translateDisplayText(locale: Locale, text: string): string {
  if (locale !== 'zh-CN') return text
  const floor = text.match(/^Floor (\d+)$/)
  if (floor) return `${floor[1]} 层`
  const basement = text.match(/^Basement (\d+)$/)
  if (basement) return `地下 ${basement[1]} 层`
  const pointCount = text.match(/^(\d+) \/ 128 points$/)
  if (pointCount) return `${pointCount[1]} / 128 个点`
  const selectedPointCount = text.match(/^(\d+) points$/)
  if (selectedPointCount) return `${selectedPointCount[1]} 个点`
  const registeredPointCount = text.match(
    /^(\d+) points registered\. The river is ready to finish\.$/,
  )
  if (registeredPointCount) return `已设置 ${registeredPointCount[1]} 个点，可以完成河流。`
  let match = text.match(
    /^Drainage reserves ([\d.]+) m gutters; hydrants reserve a ([\d.]+) m roadside verge\.$/,
  )
  if (match) return `排水设施预留 ${match[1]} m 路缘排水带；消防栓预留 ${match[2]} m 路侧绿化带。`
  match = text.match(/^([\d.]+) m plan · ([\d.]+) m vertical$/)
  if (match) return `平面容差 ${match[1]} m · 竖向容差 ${match[2]} m`
  match = text.match(/^(\d+) changes$/)
  if (match) return `${match[1]} 项变更`
  match = text.match(/^(\d+) validation issues? will remain after cleanup\.$/)
  if (match) return `清理后仍将保留 ${match[1]} 项验证问题。`
  match = text.match(/^(\d+) road segments? selected$/)
  if (match) return `已选择 ${match[1]} 个道路分段`
  match = text.match(/^Copied (\d+) road segments? as JSON\.$/)
  if (match) return `已将 ${match[1]} 个道路分段复制为 JSON。`
  match = text.match(/^Review (\d+) proposed cleanup changes? before applying\.$/)
  if (match) return `应用前请复核 ${match[1]} 项清理变更。`
  match = text.match(/^Applied (\d+) reviewed cleanup changes?\.$/)
  if (match) return `已应用 ${match[1]} 项经复核的清理变更。`
  match = text.match(/^(?:Replaced the selected road with|Imported) (\d+) road segments?\.$/)
  if (match)
    return `${text.startsWith('Replaced') ? '已替换选中道路，共' : '已导入'} ${match[1]} 个道路分段。`
  match = text.match(/^Remove edge (.+)$/)
  if (match) return `移除边 ${match[1]}`
  match = text.match(/^Repair style on (.+)$/)
  if (match) return `修复 ${match[1]} 的样式`
  match = text.match(/^Merge node (.+) into (.+)$/)
  if (match) return `将节点 ${match[1]} 合并到 ${match[2]}`
  match = text.match(/^Snap (.+) to (.+)$/)
  if (match) return `将 ${match[1]} 吸附到 ${match[2]}`
  match = text.match(/^Create crossing at (.+)$/)
  if (match) return `在 ${match[1]} 创建交叉口`
  match = text.match(/^Remove isolated node (.+)$/)
  if (match) return `移除孤立节点 ${match[1]}`
  match = text.match(/^Rebuild junction (.+)$/)
  if (match) return `重建交叉口 ${match[1]}`
  match = text.match(/^Its plan length is below ([\d.]+) m\.$/)
  if (match) return `其平面长度小于 ${match[1]} m。`
  match = text.match(/^It duplicates edge (.+)\.$/)
  if (match) return `它与边 ${match[1]} 重复。`
  match = text.match(/^Replace missing active style (.+) with (.+)\.$/)
  if (match) return `将缺失的当前样式 ${match[1]} 替换为 ${match[2]}。`
  match = text.match(/^Replace missing style (.+) with (.+)\.$/)
  if (match) return `将缺失的样式 ${match[1]} 替换为 ${match[2]}。`
  match = text.match(
    /^The nodes are ([\d.]+) m apart at a compatible level\. Incident edges and junction state will use (.+)\.$/,
  )
  if (match) return `节点在兼容标高下相距 ${match[1]} m；关联边和交叉口状态将使用 ${match[2]}。`
  match = text.match(
    /^Move the dangling endpoint ([\d.]+) m to the compatible road centerline and split that edge at the new T-junction\.$/,
  )
  if (match) return `将悬空端点移动 ${match[1]} m 至兼容的道路中心线，并在新 T 形交叉口处分割该边。`
  match = text.match(
    /^Split (.+) and (.+) at their same-level centerline crossing and connect all four approaches\.$/,
  )
  if (match) return `在 ${match[1]} 与 ${match[2]} 的同标高中心线交点处分割，并连接四个进口。`
  match = text.match(
    /^No road edge references this node(; its stale junction record is removed too)?\.$/,
  )
  if (match)
    return match[1]
      ? '没有道路边引用此节点；其过期的交叉口记录也将删除。'
      : '没有道路边引用此节点。'
  match = text.match(/^(.*) Also removes (\d+) attached asset references?\.$/)
  if (match)
    return `${translateDisplayText(locale, match[1]!)}同时移除 ${match[2]} 个关联资产引用。`
  return displayMessages[text] ?? text
}

type I18nValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: MessageKey) => string
  translateDisplayText: (text: string) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>('en')

  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY)
    const next =
      saved === 'en' || saved === 'zh-CN'
        ? saved
        : navigator.language.startsWith('zh')
          ? 'zh-CN'
          : 'en'
    setLocale(next)
  }, [])

  useEffect(() => {
    document.documentElement.lang = locale
    localStorage.setItem(STORAGE_KEY, locale)
    document.cookie = `${STORAGE_KEY}=${locale}; path=/; max-age=31536000; samesite=lax`
  }, [locale])

  const value = useMemo<I18nValue>(
    () => ({
      locale,
      setLocale,
      t: (key) => translate(locale, key),
      translateDisplayText: (text) => translateDisplayText(locale, text),
    }),
    [locale],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
