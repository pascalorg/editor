describe('frozen surface hosting parity', () => {
  for (const [adapter, accepted, refused] of [
    ['item', 18, 10],
    ['shelf', 498, 88],
    ['procedural-item', 100, 3],
  ] as const) {
    test(`${adapter}: frozen case count and both verdicts`, () => {
      const expected =
        adapter === 'procedural-item'
          ? frozenProceduralParity
              .filter((fixture) => (fixture.host as AnyNode).type === adapter)
              .flatMap((fixture) => fixture.rows.map((row) => row.expected))
          : frozenParity
              .filter((fixture) => (fixture.host as AnyNode).type === adapter)
              .flatMap((fixture) => fixture.rows.map((row) => row[6]))
      const acceptedCount = expected.filter((result) => result !== null).length
      const refusedCount = expected.filter((result) => result === null).length
      expect(acceptedCount).toBeGreaterThan(0)
      expect(refusedCount).toBeGreaterThan(0)
      expect({ total: expected.length, accepted: acceptedCount, refused: refusedCount }).toEqual({
        total: accepted + refused,
        accepted,
        refused,
      })
    })
  }

  for (const fixture of frozenParity)
    for (const [
      index,
      [point, size, yaw, normalY, grid, snapped, expected, scenario],
    ] of fixture.rows.entries())
      test(`${fixture.label}; case ${index + 1}${scenario ? `; ${scenario}` : ''}`, () => {
        const restore = nodeRegistry._snapshot()
        nodeRegistry._reset()
        try {
          registerHostingTestNode({
            kind: 'item',
            schemaVersion: 1,
            schema: ItemNode,
            category: 'furnish',
            defaults: () => ({}),
            capabilities: {},
          })
          const host = fixture.host as AnyNode
          if (host.type === 'shelf') {
            registerHostingTestNode({
              kind: 'shelf',
              schemaVersion: 1,
              schema: ShelfNode,
              category: 'furnish',
              defaults: () => ({}),
              capabilities: {
                surfaces: {
                  custom: (node) =>
                    shelfRowSurfaceYs(node as ShelfNode).map((y) => ({
                      position: [0, y, 0],
                      normal: [0, 1, 0],
                    })),
                },
              },
            })
          }
          for (const childKind of ['item', 'procedural-item']) {
            const result = resolveSurfacePlacement({
              host,
              childKind,
              childId: (childKind === 'item' ? ItemNode : ProceduralItemNode).shape.id.parse(
                undefined,
              ),
              childFootprint: { size, rotationY: yaw },
              hit: { point, normalWorldY: normalY },
              scene: { get: () => undefined, nodes: () => ({}) } as unknown as SceneApi,
              snapScalar:
                grid === 0
                  ? undefined
                  : (p, d) => {
                      const axis = p === point[0] ? 0 : 1
                      expect(d).toBe(size[axis * 2]!)
                      const snappedPosition = snapToGrid(p, d, grid)
                      expect(snappedPosition).toBe(snapped[axis]!)
                      return snappedPosition
                    },
            })
            expect(result !== null).toBe(expected !== null)
            if (expected) {
              expect(result!.position).toEqual(expected.position)
              expect(result!.rotationY).toBeCloseTo(expected.rotationY)
              expect(result!.childFrame).toBe('host-local')
              expect(result!.surfaceLocal === null).toBe(host.type === 'item')
              expect(result!.surfaceId).toBe(
                host.type === 'shelf'
                  ? `row:${shelfRowSurfaceYs(host).indexOf(expected.position[1]!)}`
                  : null,
              )
            }
          }
        } finally {
          restore()
        }
      })

  for (const fixture of frozenProceduralParity)
    for (const [index, row] of fixture.rows.entries())
      test(`procedural ${fixture.label}; case ${index + 1}`, () => {
        const restore = nodeRegistry._snapshot()
        nodeRegistry._reset()
        try {
          registerHostingTestNode({
            kind: 'procedural-item',
            schemaVersion: 1,
            schema: ProceduralItemNode,
            category: 'furnish',
            defaults: () => ({}),
            capabilities: {},
          })
          const { expected, rejections, ...args } = row
          const rejected: string[] = []
          const result = resolveSurfacePlacement({
            ...args,
            childId: (args.childKind === 'procedural-item'
              ? ProceduralItemNode
              : ItemNode
            ).shape.id.parse(undefined),
            host: fixture.host as AnyNode,
            scene: { get: () => undefined, nodes: () => ({}) } as unknown as SceneApi,
            onReject: (reason) => rejected.push(reason),
          })
          expect(result).toEqual(expected)
          expect(rejected).toEqual(rejections)
        } finally {
          restore()
        }
      })
})
