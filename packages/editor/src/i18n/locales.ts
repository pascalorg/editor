let registered = false

export function registerBundledLocales(): void {
  if (registered) return
  registered = true
  for (const [locale, namespaces] of Object.entries(bundledLocalePacks)) {
    registerMessages(locale, 'core', namespaces.core)
    registerMessages(locale, 'editor', namespaces.editor)
    registerMessages(locale, 'viewer', namespaces.viewer)
  }
}
