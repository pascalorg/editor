function translateDynamicText(text: string): string | null {
  const colonLabel = text.match(/^(.+):$/)
  const colonKey = colonLabel?.[1]
  if (colonKey && tr[colonKey]) return `${tr[colonKey]}:`

  const nodeCount = text.match(/^(\d+) nodes?$/)
  if (nodeCount) return `${nodeCount[1]} düğüm`

  const sceneCount = text.match(/^(\d+) scenes?\.$/)
  if (sceneCount) return `${sceneCount[1]} sahne.`

  const segment = text.match(/^Segment (\d+)$/)
  if (segment) return `Bölüm ${segment[1]}`

  const saveFailed = text.match(/^Save failed(?: \((\d+)\))?$/)
  if (saveFailed)
    return saveFailed[1] ? `Kaydetme başarısız (${saveFailed[1]})` : 'Kaydetme başarısız'

  const levels = text.match(/^Levels: (.+)$/)
  const levelLabel = levels?.[1]
  if (levelLabel) return `Katlar: ${tr[levelLabel] ?? levelLabel}`

  const walls = text.match(/^Walls: (.+)$/)
  const wallLabel = walls?.[1]
  if (wallLabel) return `Duvarlar: ${tr[wallLabel] ?? wallLabel}`

  const createFailed = text.match(/^Failed to create scene \((\d+)\)$/)
  if (createFailed) return `Sahne oluşturulamadı (${createFailed[1]})`

  const saveAsFailed = text.match(/^Save-as failed \((\d+)\)$/)
  if (saveAsFailed) return `Farklı kaydetme başarısız (${saveAsFailed[1]})`

  const instances = text.match(/^(\d+) instances?$/)
  if (instances) return `${instances[1]} örnek`

  const selectedObjects = text.match(/^(\d+) objects selected$/)
  if (selectedObjects) return `${selectedObjects[1]} nesne seçildi`

  const level = text.match(/^Level (-?\d+)$/)
  if (level) return `Kat ${level[1]}`

  const zone = text.match(/^Zone (\(.+\))$/)
  if (zone) return `Bölge ${zone[1]}`

  const measure = text.match(/^Measure: (.+)$/)
  const measureLabel = measure?.[1]
  if (measureLabel) return `Ölç: ${tr[measureLabel] ?? measureLabel}`

  const snapping = text.match(/^Snapping: (.+)$/)
  const snappingLabel = snapping?.[1]
  if (snappingLabel) return `Yakalama: ${tr[snappingLabel] ?? snappingLabel}`

  const grid = text.match(/^Grid: (.+)$/)
  if (grid?.[1]) return `Izgara: ${grid[1]}`

  const gridStep = text.match(/^Grid step: (.+)$/)
  if (gridStep?.[1]) return `Izgara adımı: ${gridStep[1]}`

  const continuation = text.match(/^Continuation: (.+)$/)
  const continuationLabel = continuation?.[1]
  if (continuationLabel) return `Devam: ${tr[continuationLabel] ?? continuationLabel}`

  const justify = text.match(/^Justify: (.+)$/)
  const justifyLabel = justify?.[1]
  if (justifyLabel) return `Hizalama: ${tr[justifyLabel] ?? justifyLabel}`

  const reorder = text.match(/^Reorder (.+)$/)
  const reorderLabel = reorder?.[1]
  if (reorderLabel) return `${tr[reorderLabel] ?? reorderLabel} sırasını değiştir`

  const expertOnlyTool = text.match(/^(.+) is available in Expert mode\.$/)
  const expertOnlyToolLabel = expertOnlyTool?.[1]
  if (expertOnlyToolLabel)
    return `${tr[expertOnlyToolLabel] ?? expertOnlyToolLabel} yalnızca Uzman modunda kullanılabilir.`

  const canceledExpertDraft = text.match(
    /^Switched to Default\. The unfinished (.+) draft was canceled; saved Expert annotations are hidden, not deleted\.$/,
  )
  const canceledExpertDraftLabel = canceledExpertDraft?.[1]
  if (canceledExpertDraftLabel)
    return `Varsayılan moda geçildi. Tamamlanmamış ${tr[canceledExpertDraftLabel] ?? canceledExpertDraftLabel} taslağı iptal edildi; kaydedilmiş Uzman açıklamaları gizlendi, silinmedi.`

  const imageScale = text.match(/^Image will scale (.+)x from the first point\.$/)
  if (imageScale?.[1]) return `Görsel ilk noktaya göre ${imageScale[1]} kat ölçeklenecek.`

  return null
}

export function translate(text: string, locale = useUiPreferences.getState().locale): string {
  if (locale === 'en' || text.length === 0) return text

  const match = text.match(/^(\s*)(.*?)(\s*)$/s)
  if (!match) return text
  const leading = match[1] ?? ''
  const content = match[2] ?? ''
  const trailing = match[3] ?? ''
  const translated = tr[content] ?? translateDynamicText(content)
  return translated ? `${leading}${translated}${trailing}` : text
}

export function translateReactNode(node: ReactNode, locale: UiLocale): ReactNode {
  if (locale === 'en') return node
  if (typeof node === 'string') return translate(node, locale)
  if (Array.isArray(node)) {
    return node.map((child, index) => {
      const translatedChild = translateReactNode(child, locale)
      if (isValidElement(translatedChild) && translatedChild.key === null) {
        return cloneElement(translatedChild, { key: `localized-${index}` })
      }
      return translatedChild
    })
  }
  if (!isValidElement<Record<string, unknown>>(node)) return node

  const nextProps: Record<string, unknown> = {}
  for (const propName of [
    'aria-label',
    'alt',
    'badge',
    'description',
    'emptyMessage',
    'heading',
    'label',
    'placeholder',
    'status',
    'title',
  ]) {
    const value = node.props[propName]
    if (typeof value === 'string') nextProps[propName] = translate(value, locale)
  }
  if ('children' in node.props) {
    nextProps.children = translateReactNode(node.props.children as ReactNode, locale)
  }

  return cloneElement(node, nextProps)
}

export function useTranslation() {
  const locale = useUiPreferences((state) => state.locale)
  return useCallback((text: string) => translate(text, locale), [locale])
}

export function LocalizedContent({ children }: { children: ReactNode }) {
  const locale = useUiPreferences((state) => state.locale)
  return <Fragment>{translateReactNode(children, locale)}</Fragment>
}
